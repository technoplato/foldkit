import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

describe('Puzzle Expo Instant host', () => {
  it('keeps Instant out of the Expo window', () => {
    const viewSource = readFileSync('src/App.tsx', 'utf8')
    expect(viewSource).toContain('useModel(Path())')
    expect(viewSource).toContain('useScreen(Path())')
    expect(viewSource).toContain('paintScreen')
    expect(viewSource).toContain('Starting')
    expect(viewSource).toContain('Failed')
    expect(viewSource).toContain('describePuzzleSyncError')
    expect(viewSource).not.toContain('useActions(Path())')
    expect(viewSource).not.toContain('ReplicateStep')
    expect(viewSource).not.toContain('StartingWindow')
    expect(viewSource).not.toContain('signIn')
    expect(viewSource).not.toContain("useModel('/puzzle')")
    expect(viewSource).not.toContain('@instantdb')
    expect(viewSource).not.toContain('@foldkit/instant')
    expect(viewSource).not.toContain('instantHost')
    expect(viewSource).not.toContain('nativeDatabase')
    expect(viewSource).not.toContain('ExpoLive')
    expect(viewSource).not.toContain('store.send')
    expect(viewSource).not.toContain('store.observe')
    expect(viewSource).not.toContain('void Effect')
    expect(viewSource).not.toContain('github.com')
    expect(viewSource).not.toContain('surface.live')
    expect(viewSource).not.toContain('surface.sourceUrl')
    expect(viewSource).toContain('accessibilityLabel="Actions"')
    expect(viewSource).toContain('onPress={trigger}')
    expect(viewSource).toContain("position: 'absolute'")
    expect(viewSource).toContain('Modal')
    expect(viewSource).toContain("visible={menu._tag === 'Open'}")
    expect(viewSource).toContain('ProgramKeyBindings')
    expect(viewSource).not.toContain('useActionMenuKeys')
    expect(viewSource).not.toContain('addEventListener')
    expect(viewSource).not.toContain('window.addEventListener')
  })

  it('installs Instant from ExpoLive at the composition root', () => {
    const hostSource = readFileSync('src/instantHost.ts', 'utf8')
    const entrySource = readFileSync('App.tsx', 'utf8')
    expect(hostSource).toContain("import './polyfill'")
    expect(hostSource.indexOf("import './polyfill'")).toBeLessThan(
      hostSource.indexOf("from './expoLive'"),
    )
    expect(hostSource).toContain('installSyncedPuzzleHandle')
    expect(hostSource).toContain('installScreenPuzzleHandle')
    expect(hostSource).toContain('startLivePuzzle')
    expect(hostSource).toContain('ExpoLive')
    expect(entrySource).toContain('./src/polyfill')
    expect(hostSource).not.toContain('nativeDatabase')
    expect(hostSource).not.toContain('Processor.Host.ExpoIos()')
    expect(hostSource).not.toContain('Processor.Host.ExpoAndroid()')
    expect(hostSource).not.toContain('Instant(')
    expect(hostSource).not.toContain('@foldkit/instant')
    expect(hostSource).not.toContain('@instantdb')
    expect(hostSource).not.toContain('database:')
    expect(hostSource).not.toContain('puzzle-instant-example')
    expect(hostSource).not.toContain('openLivePuzzleWindowTape')
    expect(hostSource).not.toContain('signIn')
    expect(hostSource).not.toContain('void Effect')
    expect(entrySource).toContain('startInstantPuzzle')
    expect(entrySource).not.toContain('VITE_INSTANT_APP_ID')
    expect(entrySource).not.toContain('EXPO_PUBLIC_INSTANT_APP_ID')
  })

  it('puts iOS vs Android and the native database on ExpoLive', () => {
    const layerSource = readFileSync('src/expoLive.ts', 'utf8')
    expect(layerSource).toContain('export const ExpoLive')
    expect(layerSource).toContain('Platform.OS')
    expect(layerSource).toContain('Processor.Host.ExpoIos()')
    expect(layerSource).toContain('Processor.Host.ExpoAndroid()')
    expect(layerSource).toContain('Instant(')
    expect(layerSource).toContain('@instantdb/react-native')
    expect(layerSource).toContain('InstantEngine')
    expect(layerSource).toContain(
      "Symbol.for('foldkit.puzzle.expo.nativeDatabase')",
    )
    expect(layerSource).toContain("Symbol.for('foldkit.puzzle.expo.instance')")
    expect(layerSource).not.toContain('startLivePuzzle')
    expect(layerSource).not.toContain('useModel')
    expect(layerSource).not.toContain('@foldkit/instant')
    expect(layerSource).not.toContain('@instantdb/admin')
  })
})
